// Build reverse SC→TC map at load (1-to-1 reverse)
window.SC2TC = (function() {
  const out = {};
  for (const t in window.TC2SC) {
    const s = window.TC2SC[t];
    if (!out[s]) out[s] = t;  // keep first occurrence as primary
  }
  return out;
})();

// Normalize a string to Simplified Chinese
window.toSimp = function(s) {
  if (!s) return '';
  let out = '';
  for (const ch of s) {
    out += window.TC2SC[ch] || ch;
  }
  return out;
};

// Normalize a string to Traditional Chinese (best-effort, single primary mapping)
window.toTrad = function(s) {
  if (!s) return '';
  let out = '';
  for (const ch of s) {
    out += window.SC2TC[ch] || ch;
  }
  return out;
};

// Expand simplified char to all possible traditional forms
window.expandSC = function(ch) {
  return window.SC2TC_MULTI[ch] || [window.SC2TC[ch] || ch];
};
