let last = -1

export function quoteFor(name) {
  let i = Math.floor(Math.random() * lines.length)
  if (lines.length > 1) while (i === last) i = Math.floor(Math.random() * lines.length)
  last = i
  const q = lines[i]
  return { text: q.t.replace(/\{name\}/g, name || "创作者"), by: q.by || null }
}
